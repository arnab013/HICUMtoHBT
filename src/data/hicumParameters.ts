export const PARAMETER_MAP: Record<string, HicumParameter> = Object.fromEntries(
  HICUM_PARAMETERS.map((param) => [param.id, param])
);

export const PARAMETER_SECTION_MAP: Record<ParameterSectionId, ParameterSectionMeta> =
  Object.fromEntries(
    PARAMETER_SECTIONS.map((sec) => [sec.id, sec])
  ) as Record<ParameterSectionId, ParameterSectionMeta>;

export function getParameterById(id: string): HicumParameter | undefined {
  return PARAMETER_MAP[id.toLowerCase()];
}

export function getParametersBySection(section: ParameterSectionId): HicumParameter[] {
  return HICUM_PARAMETERS.filter((param) => param.section === section);
}

export function getParametersBySubsystem(subsystem: SubsystemCategory): HicumParameter[] {
  return HICUM_PARAMETERS.filter((param) => param.subsystem === subsystem);
}

export function getParametersByPlotCategory(plotCategory: PlotCategoryId): HicumParameter[] {
  return HICUM_PARAMETERS.filter((param) => param.plotCategory === plotCategory);
}

export function getParametersByCircuitElement(elementId: string): HicumParameter[] {
  return HICUM_PARAMETERS.filter((param) => param.circuitElements.includes(elementId));
}

export function getParametersByEquation(equationId: string): HicumParameter[] {
  return HICUM_PARAMETERS.filter((param) => param.equations.includes(equationId));
}

export function searchParameters(query: string): HicumParameter[] {
  const q = query.trim().toLowerCase();
  if (!q) return HICUM_PARAMETERS;
  return HICUM_PARAMETERS.filter(
    (param) =>
      param.id.toLowerCase().includes(q) ||
      param.name.toLowerCase().includes(q) ||
      param.description.toLowerCase().includes(q) ||
      param.physicalMeaning.toLowerCase().includes(q) ||
      param.sectionTitle.toLowerCase().includes(q) ||
      param.physicalRegion.toLowerCase().includes(q)
  );
}

export function getDefaultParameterValues(useTestValues = true): Record<string, number> {
  const values: Record<string, number> = {};
  for (const param of HICUM_PARAMETERS) {
    values[param.id] = useTestValues ? param.testValue : param.defaultValue;
  }
  return values;
}
